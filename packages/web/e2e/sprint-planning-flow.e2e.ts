import type { Page, Locator } from "@playwright/test";
import type { SprintPlanResult } from "@nod/core";
import { expect, test } from "./fixtures";
import { acceptAndActivate, captureSprint, plannedSprint, sprintApi, sprintDetail } from "./support/sprint-planning";
const tab = (page: Page, name: string) => page.getByRole("tablist", { name: "Issue の表示", exact: true }).getByRole("tab", { name, exact: true });
const region = (page: Page) => page.getByRole("region", { name: "依存関係のフロー", exact: true });
const card = (scope: Page | Locator, id: string) => scope.getByRole("link", { name: new RegExp(`^${id} `) });

test("Projectの共通フローで開始前・複数Project・分岐合流・外部前提・独立Issueを表示し、開始後は旧合意の採択集合を維持する", async ({ page, nod }, info) => {
  const ws = (await nod.me.initWorkspace({ key: "FL", name: "フロー製品", path: nod.repo("flow") })).workspace;
  const projects = [await nod.me.createProject({ name: "第一" }), await nod.me.createProject({ name: "第二" })];
  const refs: string[] = [];
  for (let i = 0; i < 7; i++) refs.push((await nod.me.createIssue({ workspaceId: ws.id, title: `採択 ${i + 1}`, projectRef: String(projects[i % 2]!.id) })).id);
  const outside = await nod.me.createIssue({ workspaceId: ws.id, title: "外部前提" });
  const candidate = await nod.me.createIssue({ workspaceId: ws.id, title: "候補だけ" });
  await nod.me.updateIssue(refs[4]!, { status: "done" });
  await nod.me.updateIssue(refs[5]!, { status: "canceled", reason: "不要" });
  await nod.me.updateIssue(outside.id, { status: "done" });
  for (const [from, to] of [[outside.id, refs[0]], [refs[0], refs[1]], [refs[0], refs[2]], [refs[1], refs[3]], [refs[2], refs[3]]]) await nod.me.relateIssue(from!, { blocks: to! });
  const planned = await plannedSprint(page, ws.key, refs, { candidates: [candidate.id] });
  const before = await sprintDetail(page, planned.sprint.id);
  await page.goto(`/sprints/${planned.sprint.id}?q=存在しない検索`);
  await page.getByRole("button", { name: "計画", exact: true }).click();
  await expect(page.locator("tr[data-issue-row]")).toHaveCount(0);
  await tab(page, "フロー").click();
  await expect(tab(page, "フロー")).toBeFocused();
  await expect(card(region(page), refs[0]!)).toContainText("採択予定・開始前");
  await expect(card(region(page), outside.id)).toContainText("Sprint外・参照のみ");
  await expect(card(region(page), candidate.id)).toHaveCount(0);
  await expect(region(page).locator("svg path[marker-end]")).toHaveCount(5);
  await expect(region(page).getByText("独立したIssue 3件", { exact: true })).toBeVisible();
  await expect(card(region(page), refs[4]!)).toBeHidden();
  await region(page).getByText("完了 1件を表示", { exact: true }).click();
  await expect(card(region(page), refs[4]!)).toBeVisible();
  await captureSprint(page, "plan-before-start-flow", info);
  await page.reload();
  await expect(tab(page, "フロー")).toHaveAttribute("aria-selected", "true");
  expect((await sprintDetail(page, planned.sprint.id)).version).toBe(before.version);
  const active = await acceptAndActivate(page, planned);
  const detail = await sprintDetail(page, active.id);
  const extra = detail.items.find(i => i.sourceIssueKey === candidate.id)!;
  await sprintApi<SprintPlanResult>(page, "POST", `/sprints/${active.id}/plans`, { expectedVersion: active.version, requestKey: crypto.randomUUID(), ...planned.input, items: [...planned.input.items, { itemId: extra.id, contribution: "未合意追加", executionPlan: "未実行" }], changeReason: "範囲追加の提案" });
  await page.reload();
  await expect(card(region(page), candidate.id)).toHaveCount(0);
  await expect(card(region(page), refs[0]!)).not.toContainText("採択予定・開始前");
  await captureSprint(page, "plan-active-flow", info);
  await tab(page, "一覧").click();
  await expect(tab(page, "一覧")).toBeFocused();
  await expect(page.getByRole("region", { name: "未合意の変更案", exact: true })).toContainText("第2版");
  await expect(page.getByRole("region", { name: "表示中の計画", exact: true })).toContainText("第1版");
  await captureSprint(page, "plan-adopted-and-proposal", info);
});

test("Sprintの循環注意・狭い図内スクロール・キーボード操作をProjectと共通に保つ", async ({ page, nod }, info) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const ws = (await nod.me.initWorkspace({ key: "CY", name: "循環", path: nod.repo("cycle") })).workspace;
  const refs: string[] = [];
  for (let i = 0; i < 8; i++) refs.push((await nod.me.createIssue({ workspaceId: ws.id, title: `順序を確認する ${i}` })).id);
  for (let i = 0; i < 7; i++) await nod.me.relateIssue(refs[i]!, { blocks: refs[i + 1]! });
  await nod.me.relateIssue(refs[2]!, { blocks: refs[1]! });
  const planned = await plannedSprint(page, ws.key, refs);
  await page.goto(`/sprints/${planned.sprint.id}?section=plan&view=flow`);
  const warning = region(page).getByRole("region", { name: "循環している依存関係", exact: true });
  await expect(warning).toContainText("順序を決められません");
  const diagram = region(page).getByRole("region", { name: "依存関係の図", exact: true });
  await diagram.focus();
  await page.keyboard.press("ArrowRight");
  await expect.poll(() => diagram.evaluate(el => el.scrollLeft)).toBeGreaterThan(0);
  expect(await diagram.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await captureSprint(page, "flow-narrow-cycle-keyboard", info);
  await tab(page, "一覧").click();
  await expect(tab(page, "一覧")).toBeFocused();
  await page.getByRole("button", { name: "計画案を編集", exact: true }).click();
  await expect(page.getByRole("form", { name: "計画案の編集" }).getByLabel("今回のゴール", { exact: true })).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await captureSprint(page, "plan-editor-narrow", info);
});

test.describe("フロー取得失敗", () => {
  test.use({ allowedConsoleErrors: [/status of 400/] });
  test("再読込失敗でも最後の図と確認時刻を残し、再試行で回復する", async ({ page, nod }, info) => {
    const ws = (await nod.me.initWorkspace({ key: "ER", name: "取得確認", path: nod.repo("error") })).workspace;
    const issue = await nod.me.createIssue({ workspaceId: ws.id, title: "最後に確認したIssue" });
    const planned = await plannedSprint(page, ws.key, [issue.id]);
    await page.goto(`/sprints/${planned.sprint.id}?section=plan&view=flow`);
    await expect(card(region(page), issue.id)).toBeVisible();
    await page.route(`**/api/sprints/${planned.sprint.id}/flow*`, route => route.fulfill({ status: 400, json: { error: { code: "INVALID_ARGS", message: "読取を再試行してください" } } }));
    await tab(page, "一覧").click(); await tab(page, "フロー").click();
    await expect(region(page).getByRole("alert")).toContainText("最後の確認");
    await expect(card(region(page), issue.id)).toBeVisible();
    await captureSprint(page, "flow-last-graph-on-error", info);
    await page.unroute(`**/api/sprints/${planned.sprint.id}/flow*`);
    await region(page).getByRole("button", { name: "再試行", exact: true }).click();
    await expect(region(page).getByRole("alert")).toHaveCount(0);
  });
  test("計画0件・読み込み中・初回失敗を混同しない", async ({ page, nod }, info) => {
    const ws = (await nod.me.initWorkspace({ key: "ZE", name: "0件確認", path: nod.repo("zero") })).workspace;
    const planned = await plannedSprint(page, ws.key, []);
    let release!: () => void;
    const gate = new Promise<void>(resolve => { release = resolve; });
    await page.route(`**/api/sprints/${planned.sprint.id}/flow*`, async route => { await gate; await route.fulfill({ status: 400, json: { error: { code: "INVALID_ARGS", message: "取得失敗の検証" } } }); });
    await page.goto(`/sprints/${planned.sprint.id}?section=plan&view=flow`);
    await expect(region(page).getByRole("status")).toHaveText("読み込み中…");
    release();
    await expect(region(page).getByRole("alert")).toContainText("取得失敗の検証");
    await expect(region(page).getByText("Issue はありません", { exact: true })).toHaveCount(0);
    await page.unroute(`**/api/sprints/${planned.sprint.id}/flow*`);
    await region(page).getByRole("button", { name: "再試行", exact: true }).click();
    await expect(region(page).getByText("Issue はありません", { exact: true })).toBeVisible();
    await captureSprint(page, "flow-empty-after-retry", info);
  });
});
