import { openDb } from "../src/db";
import { afterEach, expect, setSystemTime, test } from "bun:test";
import { setup } from "./helpers";
import { createIssue, updateIssue } from "../src/ops/issues";
import { initWorkspace } from "../src/ops/workspaces";
import { setReminder } from "../src/ops/reminders";
import { listNotifications } from "../src/ops/notifications";
import { getDesktopNotificationSettings, setDesktopNotificationSettings, deliverDesktopNotifications, getDesktopNotificationDelivery } from "../src/ops/desktop-notifications";

afterEach(() => setSystemTime());
test("設定は初期OFF、再保存と読み直しで最後のON時刻を保持する", () => {
  setSystemTime(new Date("2026-10-15T00:00:00Z"));
  const { db } = setup();
  expect(getDesktopNotificationSettings(db)).toEqual({ enabled: false, lastEnabledAt: null });
  expect(setDesktopNotificationSettings(db, true)).toEqual({ enabled: true, lastEnabledAt: "2026-10-15T00:00:00.000Z" });
  setSystemTime(new Date("2026-10-15T01:00:00Z"));
  expect(setDesktopNotificationSettings(db, true).lastEnabledAt).toBe("2026-10-15T00:00:00.000Z");
  expect(getDesktopNotificationSettings(db).enabled).toBe(true);
});
test("実DBから全Workspaceの期限到来とCLI先行Inboxを偽OSへ一度届け、最新タイトルとメモを保つ", async () => {
  setSystemTime(new Date("2026-10-15T00:00:00Z"));
  const { db, ws, me } = setup();
  const second = initWorkspace(db, { path: "/tmp/other", key: "OTHER" }).workspace;
  const a = createIssue(me, { workspaceId: ws.id, title: "変更前" });
  const b = createIssue(me, { workspaceId: second.id, title: "別Workspace" });
  setDesktopNotificationSettings(db, true);
  for (const issue of [a, b]) setReminder(me, issue.id, { at: "2026-10-15T00:00:02Z", note: "確認する" });
  const sent: unknown[] = [];
  const os = { permission: async () => "granted" as const, send: async (item: unknown) => { sent.push(item); } };
  await deliverDesktopNotifications(db, os);
  expect(sent).toHaveLength(0);
  setSystemTime(new Date("2026-10-15T00:00:02Z"));
  const inbox = listNotifications(db);
  updateIssue(me, a.id, { title: "最新タイトル" });
  await Promise.all([deliverDesktopNotifications(db, os), deliverDesktopNotifications(db, os)]);
  expect(sent).toHaveLength(2);
  expect(sent).toContainEqual(expect.objectContaining({ issueId: a.id, title: "最新タイトル", body: "確認する" }));
  expect(listNotifications(db)).toHaveLength(2);
  expect(getDesktopNotificationDelivery(db, inbox[0]!.id)?.state).toBe("sent");
  await deliverDesktopNotifications(db, os);
  expect(sent).toHaveLength(2);
});
test("OS失敗はfailedとして永続化し再試行せずInboxを保持する", async () => {
  setSystemTime(new Date("2026-10-15T00:00:00Z"));
  const { db, ws, me } = setup();
  const issue = createIssue(me, { workspaceId: ws.id, title: "失敗" });
  setDesktopNotificationSettings(db, true);
  setReminder(me, issue.id, { at: "2026-10-15T00:00:01Z" });
  setSystemTime(new Date("2026-10-15T00:00:01Z"));
  let attempts = 0;
  const os = { permission: async () => "granted" as const, send: async () => { attempts++; throw new Error("OS failure"); } };
  await deliverDesktopNotifications(db, os);
  await deliverDesktopNotifications(db, os);
  const inbox = listNotifications(db);
  expect(attempts).toBe(1);
  expect(inbox).toHaveLength(1);
  expect(getDesktopNotificationDelivery(db, inbox[0]!.id)?.state).toBe("failed");
});
test("設定は接続を開き直して維持し、保存失敗を成功として返さない", () => {
  setSystemTime(new Date("2026-10-15T00:00:00Z"));
  const { db } = setup();
  const path = db.filename;
  setDesktopNotificationSettings(db, true);
  db.close();
  const reopened = openDb(path);
  expect(getDesktopNotificationSettings(reopened)).toEqual({ enabled: true, lastEnabledAt: "2026-10-15T00:00:00.000Z" });
  reopened.exec("CREATE TRIGGER reject_setting BEFORE UPDATE ON desktop_notification_settings BEGIN SELECT RAISE(ABORT, '保存障害'); END");
  expect(() => setDesktopNotificationSettings(reopened, false)).toThrow();
  expect(getDesktopNotificationSettings(reopened).enabled).toBe(true);
  reopened.close();
});
