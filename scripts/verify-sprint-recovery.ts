import { Database } from "bun:sqlite";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { isAbsolute, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { openDb, getSprint, listSprints, readDocument, attachmentFile } from "../packages/core/src";

// 本番データを使わず、指定した旧版と合成fixtureだけで復旧を確認する開発用スクリプト。
const [baselineArg, outputArg] = process.argv.slice(2);
if (!baselineArg || !outputArg || !isAbsolute(baselineArg) || !isAbsolute(outputArg)) {
  throw new Error("旧版コードと未使用の隔離出力先を絶対パスで指定してください");
}
const baseline = resolve(baselineArg);
const root = resolve(outputArg);
if (existsSync(root)) throw new Error("出力先は未使用ディレクトリにしてください");
const old = await import(pathToFileURL(join(baseline, "packages/core/src/index.ts")).href);
if (old.SCHEMA_VERSION !== 42) throw new Error("旧版はschema42のコードを指定してください");
mkdirSync(root, { recursive: true });
const refs = join(root, "references");
const workspace = join(refs, "workspace");
const attachments = join(refs, "attachments");
mkdirSync(workspace, { recursive: true });
const docPath = join(workspace, "spec.md");
const filePath = join(workspace, "evidence.txt");
const docBody = "# 復旧する要求\n旧版と同じ参照ファイルを読む。\n";
const fileBody = "合成fixtureの添付証拠\n";
writeFileSync(docPath, docBody);
writeFileSync(filePath, fileBody);
const dbPath = join(root, "fixture.db");
const legacy = old.openDb(dbPath);
const ctx = { db: legacy, actor: "me" };
const ws = old.initWorkspace(legacy, { path: workspace, key: "RST", name: "復旧検証" }).workspace;
const cycle = old.createCycle(ctx, { name: "復旧対象", startDate: "2026-01-01", endDate: "2026-01-14" });
const issue = old.createIssue(ctx, { workspaceId: ws.id, title: "移行前の要求", cycleRef: String(cycle.id) });
const doc = old.attachDocument(ctx, { issueRef: issue.id }, { path: docPath, kind: "spec" });
const attachment = old.addFileAttachment(ctx, issue.id, { path: filePath, dir: attachments, tmpRoot: root });
const storedFile = old.attachmentFile(legacy, attachment.id, attachments).abs;
legacy.close();
const bundle = join(root, "backup-set");
mkdirSync(bundle);
cpSync(refs, join(bundle, "references"), { recursive: true });
const hash = (path: string) => createHash("sha256").update(readFileSync(path)).digest("hex");
const expectedFiles = [docPath, filePath, storedFile].map(path => ({ path, sha256: hash(path) }));
const assert = (condition: unknown, message: string) => { if (!condition) throw new Error(message); };
const migrated = openDb(dbPath);
const periods = listSprints(migrated);
assert(periods.length === 1 && periods[0]?.phase === "imported", "全期間のimported移行");
assert(getSprint(migrated, periods[0]!.id).items[0]?.sourceIssueKey === issue.id, "元Issue関連");
assert(readDocument(migrated, doc.id).content === docBody, "移行後Document読取");
assert(hash(attachmentFile(migrated, attachment.id, attachments).abs) === expectedFiles[2]!.sha256, "移行後添付読取");
assert(migrated.query("PRAGMA foreign_key_check").all().length === 0, "移行後FK整合性");
const beforeReopen = JSON.stringify(getSprint(migrated, periods[0]!.id));
migrated.close();
const backups = readdirSync(join(root, "backups")).filter(name => name.endsWith("-v42.db"));
assert(backups.length === 1, "版42の移行前バックアップ1件");
const backup = join(root, "backups", backups[0]!);
cpSync(backup, join(bundle, "pre-migration.db"));
const reopened = openDb(dbPath);
assert(JSON.stringify(getSprint(reopened, periods[0]!.id)) === beforeReopen, "同DB再オープンの冪等性");
assert(readdirSync(join(root, "backups")).filter(name => name.endsWith("-v42.db")).length === 1, "バックアップ再生成なし");
reopened.close();
const backupDb = new Database(backup, { readonly: true });
assert(JSON.stringify(backupDb.query("PRAGMA integrity_check").all()) === '[{"integrity_check":"ok"}]', "バックアップ整合性");
assert(backupDb.query("PRAGMA foreign_key_check").all().length === 0, "バックアップFK整合性");
backupDb.close();
// 障害は合成fixtureの参照ファイルだけに限定する。絶対Documentパスも同じ場所へ復旧する。
rmSync(refs, { recursive: true });
cpSync(join(bundle, "references"), refs, { recursive: true });
const restoredPath = join(root, "restored.db");
cpSync(join(bundle, "pre-migration.db"), restoredPath);
const restored = old.openDb(restoredPath);
assert(old.schemaVersion(restored) === 42, "旧版schema42");
assert(old.listCycles(restored)[0]?.name === "復旧対象", "旧版の期間読取");
assert(old.getIssue(restored, issue.id).cycle?.id === cycle.id, "旧版の所属読取");
assert(old.readDocument(restored, doc.id).content === docBody, "復旧後Document読取");
assert(readFileSync(old.attachmentFile(restored, attachment.id, attachments).abs, "utf8") === fileBody, "復旧後添付読取");
assert(expectedFiles.every(file => hash(file.path) === file.sha256), "対応参照ファイルのhash一致");
assert(restored.query("PRAGMA foreign_key_check").all().length === 0, "復旧後FK整合性");
old.updateIssue({ db: restored, actor: "me" }, issue.id, { title: "復旧後の通常更新" });
assert(old.getIssue(restored, issue.id).title === "復旧後の通常更新", "旧版の通常更新");
restored.close();
const report = { result: "成功", baseline, root, dbPath, backup, bundle, restoredPath, source: "合成fixtureのみ", expectedFiles, checks: ["移行前の整合した版42バックアップ", "公開操作で移行と参照ファイル読取", "移行後と復旧後のFK整合性", "同DB再オープンの冪等性", "旧版公開APIの期間と所属と文書と添付読取", "対応参照ファイルの復旧とhash一致", "旧版公開APIの通常更新"] };
writeFileSync(join(root, "result.json"), JSON.stringify(report, null, 2) + "\n");
console.log(JSON.stringify(report, null, 2));
